export function getMiraKnowledgeReply(input) {
  const text = normalizeBanglishText(input);
  if (!text) return null;

  const intent = classifyMiraIntent(text);
  if (intent === 'cooking_problem') {
    const reply = getCookingTroubleshootingReply(text);
    if (!/চলো, সমস্যা ঠিক করি/u.test(reply)) return reply;
  }

  for (const item of COOKING_KNOWLEDGE) {
    if (item.pattern.test(text)) return item.reply;
  }

  if (/(^|\s)(mira|মিরা)(\s|$)/u.test(text) && /(help|সাহায্য|কী পার|কি পার|can you|পারো)/u.test(text)) {
    return 'আমি Mira*—Rannar Menu-র নিজস্ব রান্নাঘর-সহকারী। রেসিপি ক্যাটালগে খোঁজা, রান্নার ভুল ঠিক করা, মাপ/সময় বোঝানো ও সাইট ব্যবহার—এগুলোতে সাহায্য করি। প্রশ্নটা বলো, ধাপে ধাপে এগোব।';
  }
  return null;
}

export function getMiraLocalRecipeGuide(input) {
  const text = normalizeBanglishText(input);
  if (!text) return null;
  const guide = LOCAL_GUIDES.find(item => item.pattern.test(text));
  return guide ? guide.text : null;
}

